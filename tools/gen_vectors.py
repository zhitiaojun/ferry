#!/usr/bin/env python3
"""Generate protocol test vectors for docs/spec/protocol.md.

This encoder is written independently of the Go implementation in core/proto,
so decoding the generated bytes with Go is a real cross-check, not a
round-trip through the same code.

Usage (from the repository root):
    python tools/gen_vectors.py
"""

import argparse
import hashlib
import json
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUT = ROOT / "docs" / "spec" / "vectors"
OUT = DEFAULT_OUT  # resolved from --out in main()

MAGIC = b"FTRX"
VERSION = 1


def u8(v):
    return bytes([v])


def u16(v):
    return struct.pack(">H", v)


def u32(v):
    return struct.pack(">I", v)


def u64(v):
    return struct.pack(">Q", v)


def i64(v):
    return struct.pack(">q", v)


def hx(b):
    return b.hex()


def frame(msg_type, session_id, seq, payload, magic=MAGIC, version=VERSION, flags=0):
    return (
        magic
        + u8(version)
        + u8(msg_type)
        + u16(flags)
        + session_id
        + u64(seq)
        + u32(len(payload))
        + payload
    )


# ---------------------------------------------------------------------------
# Fixed inputs shared by the vectors.
# ---------------------------------------------------------------------------

SID = bytes.fromhex("00112233445566778899aabbccddeeff")
DID_SENDER = hashlib.sha256(b"win-dev").digest()
DID_RECEIVER = hashlib.sha256(b"android-dev").digest()
NONCE = bytes.fromhex("a1b2c3d4e5f60718293a4b5c6d7e8f90")
TRANSFER_ID = bytes.fromhex("101112131415161718191a1b1c1d1e1f")

FILE_A = b"a" * 2100000  # 2.1 MB test file (D10)
FILE_B = b"b" * 1024
HASH_A = hashlib.sha256(FILE_A).digest()
HASH_B = hashlib.sha256(FILE_B).digest()
HASH_EMPTY = hashlib.sha256(b"").digest()

CHUNK_DATA = b"hello filetransfer"
CHUNK_HASH = hashlib.sha256(CHUNK_DATA).digest()

PING_TOKEN = bytes.fromhex("1122334455667788")


# ---------------------------------------------------------------------------
# Payload encoders (§3).
# ---------------------------------------------------------------------------


def p_hello(min_v=1, max_v=1, device_id=DID_SENDER, nonce=NONCE,
            caps=3, name="win-dev"):
    name_b = name.encode("utf-8")
    return (
        u16(min_v) + u16(max_v) + device_id + nonce + u32(caps)
        + u16(len(name_b)) + name_b
    )


def p_hello_ack(version=1, device_id=DID_RECEIVER, nonce_echo=NONCE,
                caps=3, name="android-dev"):
    name_b = name.encode("utf-8")
    return (
        u16(version) + device_id + nonce_echo + u32(caps)
        + u16(len(name_b)) + name_b
    )


def p_manifest(chunk_size=65536, files=None, transfer_id=TRANSFER_ID):
    if files is None:
        files = [
            ("a.bin", len(FILE_A), 1762500000123, HASH_A),
            ("b.txt", len(FILE_B), 1762500000456, HASH_B),
        ]
    out = transfer_id + u32(chunk_size) + u32(len(files))
    for name, size, mtime, sha in files:
        nb = name.encode("utf-8")
        out += u16(len(nb)) + nb + u64(size) + i64(mtime) + sha
    return out


def p_data(file_index=0, offset=131072, data=CHUNK_DATA, sha=CHUNK_HASH,
           transfer_id=TRANSFER_ID):
    return (
        transfer_id + u32(file_index) + u64(offset) + sha + data
    )


def p_offset(transfer_id=TRANSFER_ID, file_index=0, offset=131072):
    return transfer_id + u32(file_index) + u64(offset)


def p_fin(status=0, hashes=(HASH_A, HASH_B), transfer_id=TRANSFER_ID):
    out = u8(status) + transfer_id + u32(len(hashes))
    for h in hashes:
        out += h
    return out


def p_error(code=4, message="frame too large"):
    mb = message.encode("utf-8")
    return u16(code) + u16(len(mb)) + mb


def p_ping(token=PING_TOKEN):
    return token


# ---------------------------------------------------------------------------
# Valid vectors.
# ---------------------------------------------------------------------------


def hello_expect(name="win-dev"):
    return {
        "min_version": 1,
        "max_version": 1,
        "device_id": hx(DID_SENDER),
        "nonce": hx(NONCE),
        "capabilities": 3,
        "name": name,
    }


def manifest_expect(chunk_size=65536, files=None):
    if files is None:
        files = [
            ("a.bin", len(FILE_A), 1762500000123, HASH_A),
            ("b.txt", len(FILE_B), 1762500000456, HASH_B),
        ]
    return {
        "transfer_id": hx(TRANSFER_ID),
        "chunk_size": chunk_size,
        "files": [
            {"name": n, "size": s, "mtime_ms": m, "sha256": hx(h)}
            for (n, s, m, h) in files
        ],
    }


def valid_vector(name, msg_type, type_name, seq, payload, expect_payload):
    f = frame(msg_type, SID, seq, payload)
    return {
        "name": name,
        "frame_hex": hx(f),
        "expect": {
            "version": VERSION,
            "type": type_name,
            "type_id": msg_type,
            "flags": 0,
            "session_id": hx(SID),
            "seq": seq,
            "payload_len": len(payload),
            "payload": expect_payload,
        },
    }


def build_frames():
    vectors = [
        valid_vector("hello", 0x01, "HELLO", 0, p_hello(), hello_expect()),
        valid_vector(
            "hello_empty_name", 0x01, "HELLO", 1,
            p_hello(name=""), hello_expect(name=""),
        ),
        valid_vector(
            "hello_ack", 0x02, "HELLO_ACK", 0, p_hello_ack(),
            {
                "version": 1,
                "device_id": hx(DID_RECEIVER),
                "nonce_echo": hx(NONCE),
                "capabilities": 3,
                "name": "android-dev",
            },
        ),
        valid_vector(
            "manifest", 0x03, "MANIFEST", 2, p_manifest(), manifest_expect(),
        ),
        valid_vector(
            "manifest_empty_file", 0x03, "MANIFEST", 3,
            p_manifest(files=[("empty.bin", 0, 1762500000999, HASH_EMPTY)]),
            manifest_expect(files=[("empty.bin", 0, 1762500000999, HASH_EMPTY)]),
        ),
        valid_vector(
            "data", 0x04, "DATA", 10, p_data(),
            {
                "transfer_id": hx(TRANSFER_ID),
                "file_index": 0,
                "offset": 131072,
                "chunk_sha256": hx(CHUNK_HASH),
                "data_hex": hx(CHUNK_DATA),
            },
        ),
        valid_vector(
            "ack", 0x05, "ACK", 11, p_offset(),
            {
                "transfer_id": hx(TRANSFER_ID),
                "file_index": 0,
                "offset": 131072,
            },
        ),
        valid_vector(
            "resume", 0x06, "RESUME", 12, p_offset(offset=196608),
            {
                "transfer_id": hx(TRANSFER_ID),
                "file_index": 0,
                "offset": 196608,
            },
        ),
        valid_vector(
            "fin", 0x07, "FIN", 20, p_fin(),
            {
                "status": 0,
                "transfer_id": hx(TRANSFER_ID),
                "file_sha256": [hx(HASH_A), hx(HASH_B)],
            },
        ),
        valid_vector(
            "error", 0x08, "ERROR", 21, p_error(),
            {
                "code": 4,
                "code_name": "frame_too_large",
                "message": "frame too large",
            },
        ),
        valid_vector(
            "ping", 0x09, "PING", 30, p_ping(), {"token": hx(PING_TOKEN)},
        ),
        valid_vector(
            "pong", 0x0A, "PONG", 31, p_ping(), {"token": hx(PING_TOKEN)},
        ),
    ]
    return {
        "spec": "docs/spec/protocol.md v1.0-draft",
        "generator": "tools/gen_vectors.py",
        "vectors": vectors,
    }


# ---------------------------------------------------------------------------
# Invalid vectors: each carries the expected error name from §1.2 / §7.
# ---------------------------------------------------------------------------


def build_invalid():
    hello = p_hello()
    valid = frame(0x01, SID, 0, hello)

    bad_manifest_name = p_manifest(
        files=[("../evil", 16, 1762500000000, hashlib.sha256(b"x" * 16).digest())]
    )
    bad_chunk = p_manifest(chunk_size=1024)

    header_only = (
        MAGIC + u8(VERSION) + u8(0x01) + u16(0) + SID + u64(0) + u32(0x00100001)
    )
    zero_sid = frame(0x01, bytes(16), 0, hello)
    unknown_type = MAGIC + u8(VERSION) + u8(0x7F) + u16(0) + SID + u64(0) + u32(0)
    truncated_hello = frame(0x01, SID, 0, hello[:10])

    vectors = [
        {
            "name": "bad_magic",
            "frame_hex": hx(frame(0x01, SID, 0, hello, magic=b"FTRY")),
            "expect_error": "bad_magic",
        },
        {
            "name": "version_unsupported",
            "frame_hex": hx(frame(0x01, SID, 0, hello, version=2)),
            "expect_error": "version_unsupported",
        },
        {
            "name": "frame_too_large",
            "frame_hex": hx(header_only),
            "expect_error": "frame_too_large",
        },
        {
            "name": "zero_session",
            "frame_hex": hx(zero_sid),
            "expect_error": "protocol_violation",
        },
        {
            "name": "short_header",
            "frame_hex": hx(valid[:20]),
            "expect_error": "short_header",
        },
        {
            "name": "unknown_type",
            "frame_hex": hx(unknown_type),
            "expect_error": "unknown_type",
        },
        {
            "name": "hello_payload_truncated",
            "frame_hex": hx(truncated_hello),
            "expect_error": "payload_invalid",
        },
        {
            "name": "manifest_bad_name",
            "frame_hex": hx(frame(0x03, SID, 2, bad_manifest_name)),
            "expect_error": "manifest_invalid",
        },
        {
            "name": "manifest_bad_chunk_size",
            "frame_hex": hx(frame(0x03, SID, 2, bad_chunk)),
            "expect_error": "unsupported_chunk_size",
        },
    ]
    return {
        "spec": "docs/spec/protocol.md v1.0-draft",
        "generator": "tools/gen_vectors.py",
        "vectors": vectors,
    }


def main():
    global OUT
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out", default=str(DEFAULT_OUT),
        help="output directory (default: docs/spec/vectors)",
    )
    OUT = Path(parser.parse_args().out)
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "frames.json").write_text(
        json.dumps(build_frames(), indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    (OUT / "invalid.json").write_text(
        json.dumps(build_invalid(), indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT / 'frames.json'}")
    print(f"wrote {OUT / 'invalid.json'}")


if __name__ == "__main__":
    main()
