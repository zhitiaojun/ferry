// Package pairing implements the short-code pairing handshake (SPAKE2 over
// NIST P-256) used when two devices do not trust each other yet: a six digit
// code typed on both sides becomes a shared key without ever being sent.
package pairing

import (
	"crypto/elliptic"
	"crypto/hmac"
	"crypto/rand"
	"crypto/sha256"
	"errors"
	"math/big"
)

// Role separates the two sides. They must differ: each role blinds with its
// own fixed point (M for the initiator, N for the responder), which is what
// stops an eavesdropper from confirming a guessed code with one point test.
type Role int

const (
	RoleInitiator Role = 1
	RoleResponder Role = 2
)

const (
	versionLabel  = "FT-SPAKE2-V1"
	keyLabel      = "FT-SPAKE2-KEY"
	confirmLabel  = "FT-SPAKE2-CONFIRM"
	shareSize     = 65 // uncompressed P-256 point: 0x04 || X || Y
	minCodeDigits = 6
)

// M and N are fixed P-256 points whose discrete logarithms are unknown: they
// were generated by picking a random x and solving for y, and no scalar
// multiple was ever computed. Both are checked on load.
var (
	mX, mY = mustPoint("04a5d1daa78ead014c118f85061249709c37af727ff3926465b10f17e87594ce2a40c46c2bd922578b686a80c6734096a96b16aa6c7dc1fb5e5668aabafc426ff7")
	nX, nY = mustPoint("040f1c08c470f2711aa48b7e17539b03e4e5d92077096150828f197b6175edaef491b07736315d171ac86adde4b1c6e82a05e11a5c627ef69def7145c4313aa363")
)

var curve = elliptic.P256()

// ErrBadShare reports a malformed or off-curve share from the peer.
var ErrBadShare = errors.New("pairing: bad share")

// Exchange is one side of the handshake: Message is sent once, then Finish is
// called with the peer's message.
type Exchange struct {
	role Role
	sid  [16]byte
	w    *big.Int
	x    *big.Int
	X    []byte
	key  [32]byte
}

// Start creates a fresh exchange. sid names the session so the transcript
// cannot be replayed into a different pairing.
func Start(role Role, code string, sid [16]byte) (*Exchange, error) {
	if len(code) < minCodeDigits {
		return nil, errors.New("pairing: code too short")
	}
	if role != RoleInitiator && role != RoleResponder {
		return nil, errors.New("pairing: bad role")
	}
	x, err := rand.Int(rand.Reader, curve.Params().N)
	if err != nil {
		return nil, err
	}
	if x.Sign() == 0 {
		return nil, errors.New("pairing: degenerate scalar")
	}
	w := blind(code, sid)
	xbx, xby := curve.ScalarBaseMult(x.Bytes())
	mx, my := pickPoint(role)
	wpx, wpy := curve.ScalarMult(mx, my, w.Bytes())
	xp, yp := curve.Add(xbx, xby, wpx, wpy)
	return &Exchange{role: role, sid: sid, w: w, x: x, X: encodePoint(xp, yp)}, nil
}

// Message returns the share to send to the peer.
func (e *Exchange) Message() []byte {
	out := make([]byte, len(e.X))
	copy(out, e.X)
	return out
}

// Finish consumes the peer's share and derives the shared key. Malformed or
// off-curve points are rejected: a blind guess lands on the curve only by
// accident.
func (e *Exchange) Finish(peerShare []byte) ([32]byte, error) {
	px, py, err := decodePoint(peerShare)
	if err != nil {
		return [32]byte{}, err
	}
	// Unblind: peer - w*peerPoint, computed as peer + (-1)*(w*peerPoint).
	nx, ny := pickPoint(peerRole(e.role))
	wpx, wpy := curve.ScalarMult(nx, ny, e.w.Bytes())
	neg := new(big.Int).Sub(curve.Params().P, wpy)
	neg.Mod(neg, curve.Params().P)
	dx, dy := curve.Add(px, py, wpx, neg)
	kx, ky := curve.ScalarMult(dx, dy, e.x.Bytes())
	if kx.Sign() == 0 && ky.Sign() == 0 {
		return [32]byte{}, ErrBadShare
	}
	h := sha256.New()
	h.Write([]byte(keyLabel))
	h.Write(e.sid[:])
	// Transcript order must be identical on both sides: initiator share first.
	first, second := e.X, peerShare
	if e.role == RoleResponder {
		first, second = peerShare, e.X
	}
	h.Write(first)
	h.Write(second)
	h.Write(encodePoint(kx, ky))
	copy(e.key[:], h.Sum(nil))
	return e.key, nil
}

// ConfirmTag returns the tag each side sends after Finish; comparing tags
// proves both derived the same key, so a wrong code is caught immediately.
func ConfirmTag(key [32]byte, label string) []byte {
	m := hmac.New(sha256.New, key[:])
	m.Write([]byte(confirmLabel))
	m.Write([]byte(label))
	return m.Sum(nil)
}

// blind derives the blinding scalar from the code. Both sides must use the
// same w (the M/N points already distinguish the roles); a plain hash reduced
// mod n is enough because SPAKE2 only needs w unpredictable and transcript
// bound, not a password-hashing KDF (nothing is stored server side).
func blind(code string, sid [16]byte) *big.Int {
	h := sha256.New()
	h.Write([]byte(versionLabel))
	h.Write(sid[:])
	h.Write([]byte(code))
	w := new(big.Int).SetBytes(h.Sum(nil))
	w.Mod(w, curve.Params().N)
	if w.Sign() == 0 {
		w.SetInt64(1)
	}
	return w
}

func pickPoint(role Role) (*big.Int, *big.Int) {
	if role == RoleInitiator {
		return mX, mY
	}
	return nX, nY
}

func peerRole(role Role) Role {
	if role == RoleInitiator {
		return RoleResponder
	}
	return RoleInitiator
}

func mustPoint(h string) (*big.Int, *big.Int) {
	b := make([]byte, len(h)/2)
	for i := range b {
		var v byte
		for j := 0; j < 2; j++ {
			c := h[2*i+j]
			switch {
			case c >= '0' && c <= '9':
				v = v<<4 | (c - '0')
			case c >= 'a' && c <= 'f':
				v = v<<4 | (c - 'a' + 10)
			default:
				panic("pairing: bad constant")
			}
		}
		b[i] = v
	}
	x, y, err := decodePoint(b)
	if err != nil {
		panic("pairing: constant off curve: " + err.Error())
	}
	return x, y
}

func encodePoint(x, y *big.Int) []byte {
	out := make([]byte, shareSize)
	out[0] = 4
	copy(out[1:33], pad32(x))
	copy(out[33:], pad32(y))
	return out
}

func pad32(v *big.Int) []byte {
	b := v.Bytes()
	out := make([]byte, 32)
	copy(out[32-len(b):], b)
	return out
}

func decodePoint(b []byte) (x, y *big.Int, err error) {
	if len(b) != shareSize || b[0] != 4 {
		return nil, nil, ErrBadShare
	}
	x = new(big.Int).SetBytes(b[1:33])
	y = new(big.Int).SetBytes(b[33:])
	if !curve.IsOnCurve(x, y) {
		return nil, nil, ErrBadShare
	}
	return x, y, nil
}
